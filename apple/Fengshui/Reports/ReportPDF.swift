import UIKit

/// Renders a report as a US-Letter PDF with UIGraphicsPDFRenderer. Charts are drawn with Core
/// Graphics (no SwiftUI rendering), so this runs off the main thread.
enum ReportPDF {
    static let page = CGRect(x: 0, y: 0, width: 612, height: 792)
    static let margin: CGFloat = 48
    static var width: CGFloat { page.width - 2 * margin }
    static let disclaimer = "Generated by Fengshui from the user's own consumer devices (Apple Watch, iPhone, Apple Health). "
        + "Not a medical device; values can be inaccurate or incomplete."

    struct Output: Sendable { let data: Data; let pages: Int }

    static func render(_ r: ReportRequest, sections: [ReportSection], generatedAt: Date, timeZone: TimeZone) -> Output {
        // Two passes: the first counts pages so the footer can say "page X of Y".
        let first = draw(r, sections, generatedAt, timeZone, totalPages: nil)
        return draw(r, sections, generatedAt, timeZone, totalPages: first.pages)
    }

    private static func draw(_ r: ReportRequest, _ sections: [ReportSection], _ at: Date, _ tz: TimeZone,
                             totalPages: Int?) -> Output {
        let format = UIGraphicsPDFRendererFormat()
        format.documentInfo = [kCGPDFContextTitle as String: r.title, kCGPDFContextCreator as String: "Fengshui"]
        var pages = 0
        let data = UIGraphicsPDFRenderer(bounds: page, format: format).pdfData { ctx in
            let w = Writer(ctx: ctx, totalPages: totalPages)
            w.newPage()
            w.text(r.title, .title)
            w.text("Period: \(Fmt.period(r.startDate, r.endDate, tz))  ·  Generated \(Fmt.dateTime(at, tz))", .meta)
            if let p = r.purpose, !p.isEmpty { w.text("Purpose: \(p)", .meta) }
            if let by = r.answeredBy, r.summary?.isEmpty == false { w.text("Answered by: \(by)", .meta) }
            w.space(10)
            if let q = r.question {
                w.heading("Question")
                w.text(q, .bodyBold)
                w.space(6)
            }
            if let s = r.summary, !s.isEmpty {
                w.heading(r.kind == .question ? "Answer" : "Summary")
                for para in Fmt.paragraphs(s) { w.text(para, .body) }
                w.text("Written by an AI assistant (\(r.answeredBy ?? "Claude")) from the data in this report. "
                       + "Check it against the tables below.", .note)
                w.space(8)
            }
            let present = sections.filter { !$0.isEmpty }
            w.heading("Data included")
            if present.isEmpty { w.text("No data for the selected labels in this period.", .body) }
            w.table(["Data", "Group", "Samples", "Sources"],
                    present.map { [$0.title, $0.group, $0.count.formatted(), $0.sources.prefix(2).joined(separator: ", ")] },
                    widths: [0.34, 0.16, 0.14, 0.36])
            let missing = sections.filter(\.isEmpty).map(\.title)
            if !missing.isEmpty { w.text("No data in this period: \(missing.joined(separator: ", ")).", .note) }
            for s in present { section(w, s, tz) }
            pages = w.pageNumber
        }
        return Output(data: data, pages: pages)
    }

    private static func section(_ w: Writer, _ s: ReportSection, _ tz: TimeZone) {
        w.ensure(150)
        w.space(10)
        w.heading(s.unit.isEmpty ? s.title : "\(s.title) (\(s.unit))")
        switch s.kind {
        case .numeric:
            w.text("Readings \(s.count.formatted()) · mean \(Fmt.num(s.mean)) · min \(Fmt.num(s.min)) · max \(Fmt.num(s.max)) \(s.unit)", .body)
            w.chart(s.daily, bars: false, unit: s.unit, tz: tz, caption: "Daily average")
        case .cumulative:
            w.text("Total \(Fmt.num(s.total)) \(s.unit) · per day: mean \(Fmt.num(s.mean)), lowest \(Fmt.num(s.min)), highest \(Fmt.num(s.max))", .body)
            w.chart(s.daily, bars: true, unit: s.unit, tz: tz, caption: "Daily total")
        case .sleep:
            w.text("\(s.nights.count) nights · asleep per night: mean \(Fmt.num(s.mean)) h, shortest \(Fmt.num(s.min)) h, longest \(Fmt.num(s.max)) h", .body)
            w.chart(s.daily, bars: true, unit: "h", tz: tz, caption: "Hours asleep per night (by wake date)")
            w.table(["Night (wake date)", "Asleep", "Deep", "REM", "Awake"],
                    s.nights.suffix(31).map { [$0.date, Fmt.hm($0.asleep), Fmt.hm($0.deep), Fmt.hm($0.rem), Fmt.hm($0.awake)] },
                    widths: [0.32, 0.17, 0.17, 0.17, 0.17])
        case .workout:
            w.text("\(s.workouts.count) workouts · \(Fmt.num(s.total)) min in total", .body)
            w.table(["Date", "Type", "Minutes"],
                    s.workouts.suffix(40).map { [Fmt.dateTime(Date(timeIntervalSince1970: $0.ts), tz), $0.type, Fmt.num($0.minutes)] },
                    widths: [0.4, 0.4, 0.2])
        case .category:
            w.text("\(s.count) entries", .body)
            w.table(["Value", "Count"], s.categories.map { [$0.text.capitalized, "\($0.n)"] }, widths: [0.7, 0.3])
        }
    }

    // MARK: Layout

    enum Style {
        case title, heading, body, bodyBold, meta, note, cell, cellHeader, footer
        var font: UIFont {
            switch self {
            case .title: .systemFont(ofSize: 20, weight: .bold)
            case .heading: .systemFont(ofSize: 13, weight: .semibold)
            case .body: .systemFont(ofSize: 10)
            case .bodyBold: .systemFont(ofSize: 10, weight: .semibold)
            case .meta: .systemFont(ofSize: 9)
            case .note, .footer: .italicSystemFont(ofSize: 8)
            case .cell: .monospacedDigitSystemFont(ofSize: 8.5, weight: .regular)
            case .cellHeader: .systemFont(ofSize: 8.5, weight: .semibold)
            }
        }
        var color: UIColor { [.meta, .note, .footer].contains(self) ? .darkGray : .black }
    }

    final class Writer {
        let ctx: UIGraphicsPDFRendererContext
        let totalPages: Int?
        var y: CGFloat = 0
        var pageNumber = 0
        let bottom = ReportPDF.page.height - ReportPDF.margin - 24

        init(ctx: UIGraphicsPDFRendererContext, totalPages: Int?) {
            self.ctx = ctx
            self.totalPages = totalPages
        }

        func newPage() {
            ctx.beginPage()
            pageNumber += 1
            y = ReportPDF.margin
            let footer = "Fengshui health report · page \(pageNumber)\(totalPages.map { " of \($0)" } ?? "")"
            draw(footer, .footer, at: CGPoint(x: ReportPDF.margin, y: ReportPDF.page.height - ReportPDF.margin), width: ReportPDF.width)
            draw(ReportPDF.disclaimer, .footer, at: CGPoint(x: ReportPDF.margin, y: ReportPDF.page.height - ReportPDF.margin + 10),
                 width: ReportPDF.width)
        }

        func ensure(_ h: CGFloat) { if y + h > bottom { newPage() } }
        func space(_ h: CGFloat) { y += h }

        func attrs(_ s: Style) -> [NSAttributedString.Key: Any] {
            let p = NSMutableParagraphStyle()
            p.lineBreakMode = .byWordWrapping
            return [.font: s.font, .foregroundColor: s.color, .paragraphStyle: p]
        }

        func height(_ t: String, _ s: Style, width: CGFloat) -> CGFloat {
            ceil(NSAttributedString(string: t, attributes: attrs(s))
                .boundingRect(with: CGSize(width: width, height: .greatestFiniteMagnitude),
                              options: [.usesLineFragmentOrigin, .usesFontLeading], context: nil).height)
        }

        @discardableResult
        func draw(_ t: String, _ s: Style, at p: CGPoint, width: CGFloat) -> CGFloat {
            let h = height(t, s, width: width)
            NSAttributedString(string: t, attributes: attrs(s)).draw(with: CGRect(x: p.x, y: p.y, width: width, height: h),
                                                                      options: [.usesLineFragmentOrigin, .usesFontLeading], context: nil)
            return h
        }

        func text(_ t: String, _ s: Style) {
            let h = height(t, s, width: ReportPDF.width)
            if h > bottom - ReportPDF.margin {
                // A very long paragraph: split by lines so it can flow across pages.
                for line in t.components(separatedBy: ". ") where !line.isEmpty { text(line + (line.hasSuffix(".") ? "" : "."), s) }
                return
            }
            ensure(h)
            draw(t, s, at: CGPoint(x: ReportPDF.margin, y: y), width: ReportPDF.width)
            y += h + 3
        }

        func heading(_ t: String) {
            ensure(40)
            space(4)
            text(t, .heading)
            let c = UIGraphicsGetCurrentContext()
            c?.setStrokeColor(UIColor.lightGray.cgColor)
            c?.setLineWidth(0.5)
            c?.move(to: CGPoint(x: ReportPDF.margin, y: y))
            c?.addLine(to: CGPoint(x: ReportPDF.margin + ReportPDF.width, y: y))
            c?.strokePath()
            space(4)
        }

        func table(_ header: [String], _ rows: [[String]], widths: [CGFloat]) {
            guard !rows.isEmpty else { return }
            let rowH: CGFloat = 13
            func drawRow(_ cells: [String], _ style: Style) {
                var x = ReportPDF.margin
                for (i, cell) in cells.enumerated() {
                    let w = widths[i] * ReportPDF.width
                    let clipped = cell.count > Int(w / 4.6) ? String(cell.prefix(Int(w / 4.6) - 1)) + "…" : cell
                    draw(clipped, style, at: CGPoint(x: x, y: y), width: w - 4)
                    x += w
                }
                y += rowH
            }
            ensure(rowH * 3)
            drawRow(header, .cellHeader)
            for (i, r) in rows.enumerated() {
                if y + rowH > bottom { newPage(); drawRow(header, .cellHeader) }
                if i % 2 == 1 {
                    UIColor(white: 0.95, alpha: 1).setFill()
                    UIRectFill(CGRect(x: ReportPDF.margin, y: y - 1, width: ReportPDF.width, height: rowH))
                }
                drawRow(r, .cell)
            }
            space(4)
        }

        func chart(_ points: [DataSnapshot.Point], bars: Bool, unit: String, tz: TimeZone, caption: String) {
            guard points.count > 1 else { return }
            let h: CGFloat = 110
            ensure(h + 24)
            let left = ReportPDF.margin + 36
            let rect = CGRect(x: left, y: y + 4, width: ReportPDF.width - 36, height: h)
            let values = points.map(\.value)
            var lo = bars ? 0 : values.min()!, hi = values.max()!
            if hi - lo < 1e-9 { hi = lo + 1; lo = bars ? 0 : lo - 1 }
            let t0 = points.first!.ts, t1 = points.last!.ts
            let span = Swift.max(t1 - t0, 1)
            let xOf = { (t: Double) in rect.minX + CGFloat((t - t0) / span) * rect.width }
            let yOf = { (v: Double) in rect.maxY - CGFloat((v - lo) / (hi - lo)) * rect.height }
            let c = UIGraphicsGetCurrentContext()!
            c.setStrokeColor(UIColor(white: 0.85, alpha: 1).cgColor)
            c.setLineWidth(0.5)
            for i in 0...4 {
                let gy = rect.minY + rect.height * CGFloat(i) / 4
                c.move(to: CGPoint(x: rect.minX, y: gy)); c.addLine(to: CGPoint(x: rect.maxX, y: gy))
            }
            c.strokePath()
            draw(Fmt.num(hi), .cell, at: CGPoint(x: ReportPDF.margin, y: rect.minY - 4), width: 34)
            draw(Fmt.num(lo), .cell, at: CGPoint(x: ReportPDF.margin, y: rect.maxY - 8), width: 34)
            let tint = UIColor(red: 0.16, green: 0.42, blue: 0.75, alpha: 1)
            if bars {
                let bw = Swift.max(1.5, rect.width / CGFloat(points.count) * 0.7)
                tint.setFill()
                for p in points {
                    let x = xOf(p.ts) - (p.ts == t1 ? bw : p.ts == t0 ? 0 : bw / 2)
                    UIRectFill(CGRect(x: x, y: yOf(p.value), width: bw, height: rect.maxY - yOf(p.value)))
                }
            } else {
                c.setStrokeColor(tint.cgColor)
                c.setLineWidth(1.2)
                c.move(to: CGPoint(x: xOf(points[0].ts), y: yOf(points[0].value)))
                for p in points.dropFirst() { c.addLine(to: CGPoint(x: xOf(p.ts), y: yOf(p.value))) }
                c.strokePath()
            }
            y = rect.maxY + 2
            let firstDay = Fmt.shortDate(Date(timeIntervalSince1970: t0), tz)
            let lastDay = Fmt.shortDate(Date(timeIntervalSince1970: t1), tz)
            draw("\(caption) · \(firstDay) – \(lastDay)", .meta, at: CGPoint(x: left, y: y), width: rect.width)
            y += 16
        }
    }
}

enum Fmt {
    static func num(_ v: Double?) -> String {
        guard let v else { return "–" }
        return v.formatted(.number.precision(.fractionLength(abs(v) < 10 && v != v.rounded() ? 1 : 0)))
    }

    static func hm(_ secs: Double) -> String {
        let m = Int(secs / 60)
        return String(format: "%d:%02d", m / 60, m % 60)
    }

    private static func formatter(_ f: String, _ tz: TimeZone) -> DateFormatter {
        let d = DateFormatter()
        d.timeZone = tz
        d.locale = Locale(identifier: "en_US")
        d.dateFormat = f
        return d
    }

    static func dateTime(_ d: Date, _ tz: TimeZone) -> String { formatter("MMM d, yyyy HH:mm", tz).string(from: d) }
    static func shortDate(_ d: Date, _ tz: TimeZone) -> String { formatter("MMM d", tz).string(from: d) }

    static func period(_ start: String, _ end: String, _ tz: TimeZone) -> String {
        guard let r = ReportData.range(start: start, end: end, timeZone: tz) else { return "\(start) – \(end)" }
        let f = formatter("MMM d, yyyy", tz)
        let a = f.string(from: Date(timeIntervalSince1970: r.0))
        return start == end ? a : "\(a) – \(f.string(from: Date(timeIntervalSince1970: r.1 - 1)))"
    }

    /// Light Markdown cleanup: the PDF shows plain paragraphs and "•" bullets.
    static func paragraphs(_ md: String) -> [String] {
        md.components(separatedBy: "\n").map { line -> String in
            var l = line.trimmingCharacters(in: .whitespaces)
            l = l.replacingOccurrences(of: "**", with: "").replacingOccurrences(of: "__", with: "")
            while l.hasPrefix("#") { l = String(l.dropFirst()).trimmingCharacters(in: .whitespaces) }
            if l.hasPrefix("- ") || l.hasPrefix("* ") { l = "• " + l.dropFirst(2) }
            return l
        }
        .filter { !$0.isEmpty }
    }
}
